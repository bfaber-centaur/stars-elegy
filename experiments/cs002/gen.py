#!/usr/bin/env python3
"""Generate the CS-002 engine fuel-table corpus (PG001 2407, FleetLab).

Question: does each engine's fuel factor f(w) for warps 2..10, read from the
private binary reading, match what the original game charges a moving fleet?

Each fleet is n Small Freighters (hull 25 kT + engine + Transport Cloaking 1 +
Mole-skin Shield 1) of one engine, carrying ironium so that the fleet mass M
makes one year's charge nearly equal to f(w): the fleet moves w*w ly along x
(the waypoint is 150 ly away), so by docs/KERNEL.md "Fuel cost" the charge is
ceil(trunc(f*w*w*M/2000)/10) mg, with M chosen as the smallest mass giving
w*w*M >= 20000. That map from f to the charge is one-to-one, so the observed
charge identifies f exactly. Fleets start with fuel above tank capacity
(kept in deep space, FM-004 DK) so no fleet runs dry. Fleets at a free warp
(f = 0) start with 1 mg instead, so the ram-scoop gain (KERNEL.md) shows
which following warps are also free.

Warp 10 on an engine not rated for it may destroy ships (KERNEL.md,
BINARY-ONLY); the observed ship count is part of the result.

Player 0 gets tech 26 in every field: the game strips parts above the
owner's tech from designs (docs/ORACLE.md). Four turns (engines 0-3, 4-7, 8-11, 12-15), each one PG001 year.
Usage: gen.py PRED.json OUTDIR   (PRED.json: fuel tables + masses to predict with)
"""
import json, math, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from fmlib import PLANETS

LEG = 150
TANK = 130   # Small Freighter fuel capacity per ship


def clear(p):
    return all(math.hypot(p[0] - x, p[1] - y) >= 3 for _, x, y in PLANETS)


def charge(f, w, M):
    return -(-(f * w * w * M // 2000) // 10)


def main():
    pred = json.load(open(sys.argv[1]))      # {"engines":[{"name","mass","fuel":[11]}]}
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    rows = []
    for t in range(4):
        engines = range(4 * t, 4 * t + 4)
        spec = ["# CS-002 turn %d: generated by experiments/cs002/gen.py" % t]
        spec += ["tech %s 26" % k for k in ("energy", "weapons", "prop", "con", "elec", "bio")]
        for k, e in enumerate(engines):
            spec.append("design %d clone 1 engine %d" % (3 + k, e))
        ys = iter(range(1010, 1396, 6))
        fid = 0
        for k, e in enumerate(engines):
            E = pred["engines"][e]
            ship = 27 + E["mass"]
            for w in range(2, 11):
                M = -(-20000 // (w * w))
                n = max(1, -(-M // (ship + 70)))
                cargo = M - n * ship
                assert 0 <= cargo <= 70 * n, (e, w, M, n, cargo)
                while True:
                    y = next(ys)
                    if all(clear((1010 + LEG * s / 50, y)) for s in range(51)):
                        break
                f = E["fuel"]
                F = charge(f[w], w, M)
                gain = 0
                if f[w] == 0:
                    # free warp: 1 mg start so the ram-scoop gain is visible (KERNEL.md)
                    mult = 1
                    for step, m in ((1, 3), (2, 6), (3, 10)):
                        if w + step <= 10 and f[w + step] == 0:
                            mult = m
                        else:
                            break
                    fuel = 1
                    gain = min(n * mult * w * w, n * TANK - fuel)
                else:
                    fuel = 20000
                spec.append("fleet %d at 1010 %d ships %d:%d fuel %d cargo %d 0 0 0 wp %d %d %d   # %s warp %d M=%d"
                            % (fid, y, 3 + k, n, fuel, cargo, 1010 + LEG, y, w, E["name"], w, M))
                rows.append(dict(turn=t, fleet=fid, engine=e, name=E["name"], warp=w, ships=n, mass=M,
                                 cargo=cargo, y=y, fuel0=fuel, f_pred=f[w], charge_pred=F, gain_pred=gain,
                                 fuel_pred=fuel - F + gain,
                                 x_pred=1010 + min(LEG, w * w)))
                fid += 1
        open(os.path.join(out, "turn%d.spec" % t), "w").write("\n".join(spec) + "\n")
    with open(os.path.join(out, "predictions.tsv"), "w") as fh:
        keys = list(rows[0])
        fh.write("\t".join(keys) + "\n")
        for r in rows:
            fh.write("\t".join(str(r[k]) for k in keys) + "\n")
    print(len(rows), "fleets")


if __name__ == "__main__":
    main()
