def parse(dump, turn=1):
    """Views per player from the .M sections of `turn`, plus the host after-state."""
    V, H = {}, {'pop': {}, 'def': {}, 'msgs': []}
    cur = None
    for line in dump.splitlines():
        f = line.split(' ')[0]
        m = re.match(r'\S+\.M(\d+) file turn=(\d+)', line)
        if m:
            cur = V.setdefault(int(m.group(1)) - 1, {'fleet': {}, 'planet': {}, 'design': {}, 'sbdesign': {},
                                                       'player': {}, '_designs': [], '_counts': []}) if int(m.group(2)) == turn else None
            continue
        if f.endswith('.HST'):
            m = re.search(r' planet (\d+) owner=(-?\d+) .* pop=(\d+)', line)
            if m:
                H['pop'][int(m.group(1))] = int(m.group(3))
            m = re.search(r' pdetail (\d+) .*env=(\d+)/(\d+)/(\d+) .*defenses=(\d+)', line)
            if m:
                H['def'][int(m.group(1))] = int(m.group(5))
                H.setdefault('env', {})[int(m.group(1))] = tuple(int(m.group(i)) for i in (2, 3, 4))
            continue
        if cur is None or '.M' not in f:
            continue
        m = re.search(r' fleet owner=(\d+) id=(\d+) kind=(\d+) .*cargo=(\d+)/(\d+)/(\d+)/(\d+)(.*)', line)
        if m:
            rest = dict(kv.split('=') for kv in re.findall(r'(\w+=-?\w+)', m.group(8)))
            cur['fleet'][(int(m.group(1)), int(m.group(2)))] = {
                'kind': int(m.group(3)), 'cargo': tuple(int(m.group(i)) for i in range(4, 8)), **rest}
            continue
        m = re.search(r' seen planet (\d+) owner=(-?\d+) level=(\d+) starbase=(\w+) env=(\w+) popest=(\d+) '
                      r'defest=(\d+) surface=(\w+)', line)
        if m:
            cur['planet'][int(m.group(1))] = {'owner': int(m.group(2)), 'level': int(m.group(3)),
                                              'sb': m.group(4) == 'true', 'env': m.group(5) == 'true',
                                              'popest': int(m.group(6)), 'defest': int(m.group(7))}
            continue
        # The dump's design owner is not the design's owner (a partial design
        # prints owner=?, a full foreign one the file's player). Designs come
        # in player order, as many per player as its block's shipdesigns
        # count, so the owner is taken from the position.
        m = re.search(r' design owner=(\d+|\?) n=(\d+) .*full=(\w+)', line)
        if m and ' sbdesign ' not in line:
            k = len(cur['_designs'])
            cur['_designs'].append(None)
            o, acc = None, 0
            for p, cnt in cur['_counts']:
                if k < acc + cnt:
                    o = p
                    break
                acc += cnt
            cur['design'][(o, int(m.group(2)))] = m.group(3) == 'true'
            continue
        # a partial starbase design prints owner=? (its block carries no owner)
        m = re.search(r' sbdesign owner=(\d+|\?) n=(\d+) .*full=(\w+)', line)
        if m:
            o = -1 if m.group(1) == '?' else int(m.group(1))
            cur['sbdesign'][(o, int(m.group(2)))] = m.group(3) == 'true'
            continue
        m = re.search(r' player (\d+) shipdesigns=(\d+)', line)
        if m:
            cur['player'][int(m.group(1))] = 'full' if ' energy=' in line else 'partial'
            cur['_counts'].append((int(m.group(1)), int(m.group(2))))
    return V, H


def evaluate(case, V, H):
    cid, kind, args, exp, alt, note = case
    if kind == 'record':
        return 'REC', None, '-'
    v = V.get(args[0], {})
    if kind == 'fleet':
        fl = v.get('fleet', {}).get((args[1], args[2]))
        got = fl['kind'] if fl else 0
    elif kind == 'heading':
        fl = v.get('fleet', {}).get((args[1], args[2]))
        got = (int(fl['dx']), int(fl['dy']), int(fl['warp'])) if fl and 'dx' in fl else None
    elif kind == 'mass':
        fl = v.get('fleet', {}).get((args[1], args[2]))
        got = int(fl['mass']) if fl and 'mass' in fl else None
    elif kind == 'cargo':
        fl = v.get('fleet', {}).get((args[1], args[2]))
        got = fl['cargo'] if fl else None
    elif kind == 'planet':
        p = v.get('planet', {}).get(args[1])
        got = p['level'] if p else 0
    elif kind == 'sbbit':
        p = v.get('planet', {}).get(args[1])
        got = p['sb'] if p else None
    elif kind == 'env':
        p = v.get('planet', {}).get(args[1])
        got = p['env'] if p else None
    elif kind == 'sbdesigns':
        got = [full for (o, n), full in sorted(v.get('sbdesign', {}).items()) if o in (args[1], -1)]
    elif kind == 'design':
        got = v.get('design', {}).get((args[1], args[2]))
    elif kind == 'player':
        got = v.get('player', {}).get(args[1])
    elif kind == 'defest':
        p = v.get('planet', {}).get(args[1])
        got = p['defest'] if p else None
        n = H['def'].get(args[1])
        # SCANNING.md caps n at the defenses the planet can operate (KERNEL.md:
        # min(max defenses, ceil(P/25)), max defenses min(100, max(10, 4 hab))).
        # The committed prediction left the cap out; it is applied here after
        # the run. A planet with an axis outside the race's 15..85 range has
        # hab < 0, so max defenses 10; otherwise 4 hab is assumed not to bind.
        exp = None
        if n is not None:
            cap = math.ceil(H['pop'][args[1]] / 25)
            if any(not 15 <= e <= 85 for e in H.get('env', {}).get(args[1], ())):
                cap = min(cap, 10)
            exp = defest(min(n, cap))
            note = '%s; after-state defenses %s, operable cap %d, uncapped %d' % (note, n, cap, defest(n))
    elif kind == 'popest':
        p = v.get('planet', {}).get(args[1])
        got = p['popest'] if p else None
        u = H['pop'].get(args[1])
        s = popest_set(u) if u is not None else set()
        ok = got in s
        return ('OK' if ok else 'MISS'), got, '%s; after-state pop %s00 -> %d..%d' % (
            note, u, min(s) if s else -1, max(s) if s else -1)
    else:
        raise ValueError(kind)
    return ('OK' if got == exp else 'MISS'), got, note if kind != 'defest' else note + ' -> %s' % exp


def main():
    if len(sys.argv) >= 3 and sys.argv[1] == 'specs':
        for fn in RUNS:
            r = fn()
            open('%s/%s.spec' % (sys.argv[2], r.rid), 'w').write(r.spec())
        return
    if len(sys.argv) == 2 and sys.argv[1] == 'list':
        for fn in RUNS:
            r = fn()
            print('## %s: %s' % (r.rid.upper(), r.title))
            for cid, kind, args, exp, alt, note in r.cases:
                print('  %-22s %-9s %-14s exp %-28s alt: %s  (%s)' % (cid, kind, args, exp, alt, note))
        return
    if len(sys.argv) == 4 and sys.argv[1] == 'check':
        r = {fn.__name__: fn for fn in RUNS}[sys.argv[2]]()
        V, H = parse(open(sys.argv[3]).read())
        miss = 0
        for c in r.cases:
            st, got, note = evaluate(c, V, H)
            exp = c[3] if c[1] not in ('defest', 'popest') else ''
            if c[1] == 'defest':
                exp = note.split('-> ')[-1]
            miss += st == 'MISS'
            print('%-5s %-22s %-10s %-14s expected %-16s got %-16s %s' % (st, c[0], c[1], c[2], exp, got, note))
        print('%s: %d cases, %d misses' % (r.rid, len(r.cases), miss))
        return
    print(__doc__)
    sys.exit(2)


if __name__ == '__main__':
    main()
