def place_pair(r, vx, vy, bound, lo, ships, tag, cid, alt, sign=(1, 1)):
    dx, dy, t = offset(bound, lo)
    fin = r.fleet(1, vx + sign[0] * dx, vy + sign[1] * dy, ships, note='%s-in d2=%d bound=%d' % (cid, t, bound))
    dx, dy, t2 = offset_above(bound)
    fout = r.fleet(1, vx + sign[0] * dx, vy - sign[1] * dy, ships, note='%s-out d2=%d bound=%d' % (cid, t2, bound))
    r.case('%s-in' % cid, 'fleet', (0, 1, fin), 3, alt, '%s d2=%d bound=%d' % (tag, t, bound))
    r.case('%s-out' % cid, 'fleet', (0, 1, fout), 0, alt, '%s d2=%d bound=%d' % (tag, t2, bound))


