def pct_from_pts(u):
    if u <= 100:
        return u >> 1
    if u <= 300:
        return ((u - 100) >> 3) + 50
    if u <= 612:
        return (u - 300) // 24 + 75
    if u <= 1124:
        return ((u - 612) >> 6) + 88
    if u < 1612:
        return 97 if u >= 1380 else 96
    return 98


def cloak_bound(r, c):
    """Largest d^2 at which a c% cloaked fleet is seen by normal range r (CONFIRMED, SC-001/SC-010)."""
    k = 100 - c
    return (k * r * r // 100) * k // 100


def defest(n, v=NEUTRON):
    """Defense coverage estimate (SCANNING.md, BINARY-ONLY)."""
    if n == 0:
        return 0
    k = int(100 * (1 - v / 1000) ** min(n, 100) + 0.5)
    return max(1, min(15, (104 - k) // 6))


def popest_set(u):
    """Possible population estimates (in 400s) for u = population in 100s (SCANNING.md)."""
    if u == 0:
        return {0}
    return {max(1, min(4090, (u + r - u // 8) // 4)) for r in range(max(1, u // 4))}


def heading(dx, dy):
    """Heading vector shown for a move (dx, dy): halve both, toward zero, while either is >= 128."""
    while abs(dx) >= 128 or abs(dy) >= 128:
        dx, dy = int(dx / 2), int(dy / 2)
    return dx, dy


def heading_floor(dx, dy):
    while abs(dx) >= 128 or abs(dy) >= 128:
        dx, dy = dx >> 1, dy >> 1
    return dx, dy


def offset(d2, lo=None):
    """(dx, dy) with dx^2 + dy^2 == d2 if possible, else the largest sum below d2 (and above lo)."""
    for t in range(d2, (lo or -1), -1):
        for dx in range(math.isqrt(t), -1, -1):
            dy2 = t - dx * dx
            dy = math.isqrt(dy2)
            if dy * dy == dy2:
                return dx, dy, t
    raise ValueError(d2)


def offset_above(d2):
    t = d2 + 1
    while True:
        for dx in range(math.isqrt(t), -1, -1):
            dy2 = t - dx * dx
            dy = math.isqrt(dy2)
            if dy * dy == dy2:
                return dx, dy, t
        t += 1


class Run:
    def __init__(self, rid, title):
        self.rid, self.title = rid, title
        self.lines = ['relation 0 1 2', 'relation 1 0 2']
        for p in (0, 1):
            self.lines += ['tech %d %s 26' % (p, f) for f in ('energy', 'weapons', 'prop', 'con', 'elec', 'bio')]
            self.lines.append('research %d 0' % p)
        self.lines += ['planet 17 scanner none', 'planet 8 scanner none',
                       'sbdesign 0 0 %s = Bare' % BARE_SB, 'sbdesign 1 0 %s = Bare' % BARE_SB]
        self.nfleet = {0: 0, 1: 0}
        self.cases = []       # (cid, kind, args, expected, alt, note)

    def add(self, line):
        self.lines.append(line)

    def fleet(self, owner, x, y, ships, planet=None, fuel=100, extra='', note=''):
        fid = self.nfleet[owner]
        self.nfleet[owner] += 1
        at = ('planet %d ' % planet if planet is not None else '') + 'at %d %d' % (x, y)
        self.lines.append('fleet %d %d %s ships %s fuel %d %s' % (owner, fid, at, ships, fuel, extra)
                          + ('  # ' + note if note else ''))
        return fid

    def case(self, cid, kind, args, expected, alt='-', note=''):
        self.cases.append((cid, kind, args, expected, alt, note))

    def spec(self):
        return '# %s: %s\n# generated by experiments/sc/round2.py; do not edit by hand\n%s\n' % (
            self.rid.upper(), self.title, '\n'.join(l.rstrip() for l in self.lines))


