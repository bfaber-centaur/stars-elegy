    r1.target(13, "T-16 3 Retro, env 55/47/52 orig 50/50/50, P=87", 87, env="55,47,52", orig="50,50,50"); r1.orbit(13, "7:3")
    r1.target(14, "T-19 10 Cherry, plan nobody, P=800", 800); r1.orbit(14, "0:5", plan=1)
    r1.target(15, "T-19 10 Cherry, plan player 0 only, P=800", 800); r1.orbit(15, "0:5", plan=2)
    r1.target(16, "T-19 10 Cherry, plan player 1 only, P=800", 800); r1.orbit(16, "0:5", plan=3)
    r1.target(22, "T-19 10 Cherry, plan everyone, P=800", 800); r1.orbit(22, "0:5", plan=4)
    r1.target(18, "T-20 6+4 Cherry, first fleet attacks, second nobody, P=800", 800)
    r1.orbit(18, "0:3", plan=0); r1.orbit(18, "0:2", plan=1)
    r1.target(19, "T-20 6+4 Cherry, first fleet nobody, second attacks, P=800", 800)
    r1.orbit(19, "0:3", plan=1); r1.orbit(19, "0:2", plan=0)
    r1.target(20, "T-20 6+4 Cherry, both attack, P=800", 800)
    r1.orbit(20, "0:3"); r1.orbit(20, "0:2")
    r1.target(23, "T-13 10 Smart + 10 Cherry, P=801", 801); r1.orbit(23, "1:5"); r1.orbit(23, "0:5")

    # R2: starbases, ground combat, colonization
    r2 = Run("tk002")
    r2.target(0, "T-21/T-26/T-27 100 arriving vs P=87 excess 37, mines 20 factories 15, scanner 0", 87,
              excess=37, mines=20, factories=15, scanner=0)
    r2.arrive(0, "11:1", cargo=100, task="unload")
    r2.target(1, "T-22 100 arriving vs P=96", 96); r2.arrive(1, "11:1", cargo=100, task="unload")
    r2.target(2, "T-23 100 arriving vs P=174", 174); r2.arrive(2, "11:1", cargo=100, task="unload", dy=-20)
    r2.target(3, "T-25 600 arriving vs P=435, 20 SDI", 435, defenses=20); r2.arrive(3, "11:3", cargo=600, task="unload")
    r2.target(5, "T-26 300 arriving vs P=174, 10 SDI, mines 20 factories 15, scanner 0", 174,
              defenses=10, mines=20, factories=15, scanner=0)
    r2.arrive(5, "11:2", cargo=300, task="unload", dy=-20)
    r2.target(4, "T-28 100 arriving vs P=87 with a bare fort", 87, starbase=True); r2.arrive(4, "11:1", cargo=100, task="unload", dy=-20)
    r2.target(6, "T-5 100 in orbit (unload at waypoint 0) vs P=87", 87); r2.orbit(6, "11:1", cargo=100, task="unload")
    r2.target(18, "T-4 4 Cherry in orbit + 50 arriving vs P=9, mines 20 factories 15", 9, mines=20, factories=15)
