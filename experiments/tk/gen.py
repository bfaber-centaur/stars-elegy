    r1.target(9, "T-7 20 Cherry, P=87, 100 SDI", 87, defenses=100); r1.orbit(9, "0:10")
    r1.target(10, "T-9 20 Smart, P=870, 100 SDI", 870, defenses=100); r1.orbit(10, "1:10")
