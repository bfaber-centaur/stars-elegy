#!/usr/bin/env python3
"""Write the TK- (planet takeover) Combat Lab specs.

Each run is one 2400 -> 2401 generation of Combat Lab
(tools/fleetlab/combatlab build + pinned-turn). Every case sits on its own
planet; cases on different planets do not interact. Player 1 owns the
target planets (environment set to 50/50/50, i.e. 100% habitability for
both players' identical races), player 0 attacks. Populations are in the
file's units of 100 colonists.

  python3 experiments/tk/gen.py OUTDIR
"""
import math, os, sys

XY = {0: (1045, 1291), 1: (1071, 1087), 2: (1090, 1295), 3: (1129, 1265), 4: (1143, 1103),
      5: (1146, 1180), 6: (1166, 1017), 7: (1166, 1382), 8: (1169, 1145), 9: (1208, 1297),
      10: (1224, 1359), 11: (1243, 1123), 12: (1245, 1158), 13: (1249, 1354), 14: (1268, 1317),
      15: (1281, 1064), 16: (1284, 1383), 17: (1306, 1060), 18: (1324, 1192), 19: (1342, 1123),
      20: (1348, 1290), 21: (1359, 1121), 22: (1368, 1292), 23: (1380, 1295)}

COMMON = """\
relation 0 1 {rel01}
relation 1 0 {rel10}
tech 1 energy {energy1}
# player 0 at tech 26: in TK-001..003 run1 (tech 3) the generated year dropped
# Cherry, Smart, Peerless, LBU-17 and LBU-32 bombs from player 0's designs
tech 0 energy 26
tech 0 weapons 26
tech 0 prop 26
tech 0 con 26
tech 0 elec 26
tech 0 bio 26
# no research, so player 1's energy (best defense part) cannot change during the year
research 0 0
research 1 0
# player 0 ship designs (Mini Bomber: one engine slot, one 2-bomb slot)
design 0 0 Mini Bomber, 1 Long Hump 6, 2 Cherry Bomb = Cherry2
design 0 1 Mini Bomber, 1 Long Hump 6, 2 Smart Bomb = Smart2
design 0 2 Mini Bomber, 1 Long Hump 6, 2 Peerless Bomb = Peerless2
design 0 3 Mini Bomber, 1 Long Hump 6, 1 Lady Finger Bomb = Lady1
design 0 4 Mini Bomber, 1 Long Hump 6, 1 LBU-17 Bomb = LBU17
design 0 5 Mini Bomber, 1 Long Hump 6, 1 LBU-32 Bomb = LBU32
design 0 6 Mini Bomber, 1 Long Hump 6, 1 Hush-a-Boom = Hush1
design 0 7 Mini Bomber, 1 Long Hump 6, 1 Retro Bomb = Retro1
design 0 8 Colony Ship, 1 Long Hump 6, 1 Orbital Construction Module = OCM
design 0 9 Frigate, 1 Long Hump 6, empty, 1 Multi Contained Munition, empty = MCM
design 0 10 Frigate, 1 Long Hump 6, empty, 2 Laser, empty = Laser Frigate
design 0 11 Medium Freighter, 1 Long Hump 6, empty, empty = Freighter
design 0 12 Colony Ship, 1 Long Hump 6, 1 Colonization Module = Colonizer
# player 1 keeps its 2400 ship designs (2 = Colony Ship); its starbase design 0 is a bare fort
sbdesign 1 0 Orbital Fort = Bare Fort
# player 0 plans: tactic 4, primary any, no secondary, attack who
plan 0 0 4 1 0 1 = Enemies
plan 0 1 4 1 0 0 = Nobody
plan 0 2 4 1 0 4 = Player 0 only
plan 0 3 4 1 0 5 = Player 1 only
plan 0 4 4 1 0 3 = Everyone
"""


class Run:
    def __init__(self, name, rel01=2, rel10=2, energy1=3):
        self.name, self.lines, self.cases = name, [], []
        self.hdr = COMMON.format(rel01=rel01, rel10=rel10, energy1=energy1)
        self.fid = {0: 0, 1: 0}

    def target(self, n, case, pop, starbase=False, owner=1, **kv):
        """Player-owned target planet n with environment 50/50/50."""
        self.cases.append((case, n))
        self.lines.append(f"# {case}")
        self.lines.append(f"planet {n} owner {owner} pop {pop} starbase {0 if starbase else 'none'}")
        kv.setdefault('env', '50,50,50')
        kv.setdefault('excess', 0)
        kv.setdefault('scanner', 31)
        self.lines.append(f"planetset {n} " + " ".join(f"{k}={v}" for k, v in kv.items()))

    def unowned(self, n, case):
        self.cases.append((case, n))
        self.lines.append(f"# {case} (planet {n}, unowned)")

    def orbit(self, n, ships, owner=0, plan=0, cargo=None, task=None, fuel=200):
        i = self.fid[owner]; self.fid[owner] += 1
        x, y = XY[n]
        s = f"fleet {owner} {i} planet {n} at {x} {y} ships {ships} plan {plan} fuel {fuel}"
        if cargo: s += f" cargo 0 0 0 {cargo}"
        if task: s += f" task {task}"
        self.lines.append(s)

    def arrive(self, n, ships, owner=0, plan=0, cargo=None, task=None, fuel=200, dy=20):
        """A fleet 20 ly from planet n that arrives this turn (warp 6)."""
        i = self.fid[owner]; self.fid[owner] += 1
        x, y = XY[n]
        sy = y + dy
        near = min(math.dist((x, sy), p) for k, p in XY.items() if k != n)
        assert near > 15, (n, near)
        s = f"fleet {owner} {i} at {x} {sy} ships {ships} plan {plan} fuel {fuel}"
        if cargo: s += f" cargo 0 0 0 {cargo}"
        s += f" to {x} {y} planet {n} warp 6"
        if task: s += f" task {task}"
        self.lines.append(s)

    def write(self, out):
        with open(os.path.join(out, self.name + ".spec"), "w") as f:
            f.write(f"# {self.name}: generated by experiments/tk/gen.py\n" + self.hdr + "\n".join(self.lines) + "\n")


